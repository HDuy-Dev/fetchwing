// Generates src/content/mock-main.js (a classic script for the page's MAIN
// world) from src/lib/mock-runtime.js (an ES module used by the tests).
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export function buildMockMain(runtimeSource) {
  const body = runtimeSource.replace(/^export /gm, '');
  return `// GENERATED by scripts/sync-mock-main.mjs from src/lib/mock-runtime.js — do not edit.
(() => {
${body}
const runtime = installMockRuntime(window);
window.addEventListener('message', event => {
  const data = event.data;
  if (event.source !== window || !data || data.source !== 'fetchwing-bridge' || data.type !== 'mocks') return;
  runtime.setMocks(data.mocks);
});
window.postMessage({ source: 'fetchwing-main', type: 'ready' }, '*');
})();
`;
}

// Generates src/sandbox/script-sandbox.js (a classic script for the sandboxed
// page) from src/lib/script-runtime.js.
export function buildScriptSandbox(runtimeSource) {
  const body = runtimeSource.replace(/^export /gm, '');
  return `// GENERATED by scripts/sync-mock-main.mjs from src/lib/script-runtime.js — do not edit.
(() => {
${body}
window.addEventListener('message', async event => {
  const data = event.data;
  if (event.source !== window.parent || !data || data.source !== 'fetchwing-panel' || data.type !== 'run') return;
  let result;
  try {
    result = await runScript(String(data.script ?? ''), { response: data.response, vars: data.vars ?? {} });
  } catch (err) {
    result = { logs: [], changes: [], error: formatArg(err) };
  }
  window.parent.postMessage({ source: 'fetchwing-sandbox', type: 'result', runId: data.runId, ...result }, '*');
});
window.parent.postMessage({ source: 'fetchwing-sandbox', type: 'ready' }, '*');
})();
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const root = new URL('..', import.meta.url);
  const source = readFileSync(new URL('src/lib/mock-runtime.js', root), 'utf8');
  writeFileSync(new URL('src/content/mock-main.js', root), buildMockMain(source));
  console.log('src/content/mock-main.js updated');
  const script = readFileSync(new URL('src/lib/script-runtime.js', root), 'utf8');
  writeFileSync(new URL('src/sandbox/script-sandbox.js', root), buildScriptSandbox(script));
  console.log('src/sandbox/script-sandbox.js updated');
}

// Generates src/content/mock-main.js (a classic script for the page's MAIN
// world) from src/lib/mock-runtime.js (an ES module used by the tests).
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export function buildMockMain(runtimeSource) {
  const body = runtimeSource.replace(/^export /gm, '');
  return `// GENERATED by scripts/sync-mock-main.mjs from src/lib/mock-runtime.js — do not edit.
(() => {
${body}
const runtime = installMockRuntime(window);
window.addEventListener('message', event => {
  const data = event.data;
  if (event.source !== window || !data || data.source !== 'fetchwing-bridge' || data.type !== 'mocks') return;
  runtime.setMocks(data.mocks);
});
window.postMessage({ source: 'fetchwing-main', type: 'ready' }, '*');
})();
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const root = new URL('..', import.meta.url);
  const source = readFileSync(new URL('src/lib/mock-runtime.js', root), 'utf8');
  writeFileSync(new URL('src/content/mock-main.js', root), buildMockMain(source));
  console.log('src/content/mock-main.js updated');
}
